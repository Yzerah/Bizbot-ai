export function isWebsitePackageId(id: string | undefined | null): id is WebsitePackageId {
  return WEBSITE_PACKAGES.some((pkg) => pkg.id === id);
}

export function websitePackageName(id: string) {
  return WEBSITE_PACKAGES.find((pkg) => pkg.id === id)?.name ?? LEGACY_PACKAGE_NAMES[id] ?? id;
}

export function businessTypeLabel(id: string) {
  return TRADES.find((type) => type.id === id)?.label ?? LEGACY_BUSINESS_LABELS[id] ?? id;
}

