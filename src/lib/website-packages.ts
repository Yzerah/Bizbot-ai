export function websiteOffersJsonLd(pagePath = "/websites") {
  const pageUrl = `${OFFERS_SITE_URL}${pagePath === "/" ? "" : pagePath}`;
  const offer = (name: string, price: number, description: string) => ({
    "@type": "Offer",
    name,
    description,
    price: String(price),
    priceCurrency: "ILS",
    url: pageUrl,
  });
  return {
    "@context": "https://schema.org",
    "@type": "Service",
    name: "מערכת לידים מגוגל לקבלני שיפוצים",
    serviceType: "הקמת פרופיל Google, דף נחיתה, איסוף ביקורות ומחולל הצעות מחיר",
    provider: { "@type": "Organization", name: "BizBot", url: OFFERS_SITE_URL },
    areaServed: { "@type": "Country", name: "Israel" },
    inLanguage: "he",
    url: pageUrl,
    offers: [
      offer("הקמה", LEADS_OFFER.setupPrice, `${LEADS_OFFER.summary} דמי ההקמה משולמים אחרי אישור התוצאה.`),
      offer("תפעול חודשי", LEADS_OFFER.monthlyPrice, "תשלום חודשי אחרי שהמערכת באוויר."),
      offer(
        "הצעת השקה, הקמה",
        LEADS_OFFER.launchSetupPrice,
        `מחיר השקה לחמשת הלקוחות הראשונים. דמי הקמה ${formatShekel(LEADS_OFFER.launchSetupPrice)}.`,
      ),
      offer(
        "הצעת השקה, חודשי",
        LEADS_OFFER.launchMonthlyPrice,
        `מחיר השקה לחמשת הלקוחות הראשונים. ${formatShekel(LEADS_OFFER.launchMonthlyPrice)} לחודש.`,
      ),
    ],
  };
}
