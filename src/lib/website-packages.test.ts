import assert from "node:assert/strict";
import test from "node:test";
import {
  WEBSITE_HOSTED_PRO_BENEFIT,
  WEBSITE_HOSTING,
  WEBSITE_INCLUDED_HOSTING_MONTHS,
  WEBSITE_PACKAGES,
  websitePackageBenefits,
} from "./website-packages.ts";

test("website build prices stay put and hosting starts at 49 from month 4", () => {
  assert.deepEqual(
    WEBSITE_PACKAGES.map((pkg) => pkg.price),
    [990, 1990, 2990],
  );
  assert.equal(WEBSITE_HOSTING.price, 49);
  assert.equal(WEBSITE_INCLUDED_HOSTING_MONTHS, 3);
  assert.equal(WEBSITE_HOSTED_PRO_BENEFIT, "כולל מחולל הצעות מחיר PRO בחינם");
  assert.match(WEBSITE_HOSTING.summary, /49/);
  assert.match(WEBSITE_HOSTING.summary, /הרביעי/);

  for (const pkg of WEBSITE_PACKAGES) {
    const points = [...pkg.points, ...websitePackageBenefits()];
    assert.equal(points.filter((point) => point === WEBSITE_HOSTED_PRO_BENEFIT).length, 1);
    assert.ok(points.some((point) => point.includes("3 חודשי אחסון")));
    assert.ok(points.some((point) => point.includes("49") && point.includes("הרביעי")));
  }
});
