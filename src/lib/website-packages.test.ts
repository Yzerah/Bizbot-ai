import assert from "node:assert/strict";
import test from "node:test";
import { SITE_URL } from "./site.ts";
import {
  LEADS_OFFER,
  businessTypeLabel,
  isWebsitePackageId,
  websiteOffersJsonLd,
  websitePackageName,
} from "./website-packages.ts";

test("offer json-ld uses the production origin and the leads prices", () => {
  const data = websiteOffersJsonLd("/websites/small-business");
  assert.equal(data.url, `${SITE_URL}/websites/small-business`);
  assert.equal(data.offers[0].url, `${SITE_URL}/websites/small-business`);
  assert.equal(data.offers[0].price, String(LEADS_OFFER.setupPrice));
  assert.equal(data.offers[1].price, String(LEADS_OFFER.monthlyPrice));
  assert.equal(data.name, "מערכת לידים מגוגל לקבלני שיפוצים");
});

test("the public offer is setup plus monthly, with a launch price for five clients", () => {
  assert.equal(LEADS_OFFER.id, "google-leads");
  assert.equal(LEADS_OFFER.setupPrice, 1490);
  assert.equal(LEADS_OFFER.monthlyPrice, 249);
  assert.equal(LEADS_OFFER.launchClients, 5);
  assert.equal(LEADS_OFFER.launchSetupPrice, 990);
  assert.equal(LEADS_OFFER.launchMonthlyPrice, 199);
  assert.equal(LEADS_OFFER.guaranteeDays, 90);
  assert.equal(isWebsitePackageId("google-leads"), true);
  assert.equal(isWebsitePackageId("landing"), false);
  assert.equal(isWebsitePackageId("business"), false);
});

test("older lead rows still get a Hebrew label", () => {
  assert.equal(websitePackageName("google-leads"), "מערכת לידים מגוגל");
  assert.equal(websitePackageName("landing"), "דף נחיתה (מחירון קודם)");
  assert.equal(websitePackageName("business"), "אתר עסקי (מחירון קודם)");
  assert.equal(businessTypeLabel("renovation"), "שיפוצים כלליים");
  assert.equal(businessTypeLabel("contractor"), "קבלן (טופס קודם)");
});
