#!/usr/bin/env node
// Picks the right Prisma schema from DATABASE_URL and runs Prisma tasks.
//   DATABASE_URL=file:...          -> SQLite  (prisma/sqlite/schema.prisma, derived)
//   DATABASE_URL=postgres(ql)://   -> Postgres (prisma/schema.prisma)
//   DATABASE_URL unset             -> Postgres client is generated, migrations skipped
//
// Usage: node scripts/prisma.mjs <generate|migrate|setup|dev-migrate> [extra args]
//   generate     prisma generate for the selected provider
//   migrate      prisma migrate deploy (skipped with a warning if DATABASE_URL is unset,
//                except on a Vercel production build, where it fails)
//   setup        migrate + generate (used by `npm run build`)
//   dev-migrate  prisma migrate dev (create a new migration) for the selected provider
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");

// Load .env like Prisma/Next do (without overriding real env vars).
const envFile = path.join(root, ".env");
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
    if (!m || process.env[m[1]] !== undefined) continue;
    process.env[m[1]] = m[2].replace(/^(['"])(.*)\1$/, "$2");
  }
}

const url = process.env.DATABASE_URL || "";
// Migrations should use an unpooled connection. Neon's Vercel integration exposes it
// as DATABASE_URL_UNPOOLED; fall back to DATABASE_URL so a single URL also works.
if (!process.env.DIRECT_URL) {
  const direct =
    process.env.DATABASE_URL_UNPOOLED || process.env.POSTGRES_URL_NON_POOLING || url;
  if (direct && !url.startsWith("file:")) process.env.DIRECT_URL = direct;
}
const isSqlite = url.startsWith("file:");
const PG_SCHEMA = "prisma/schema.prisma";
const SQLITE_SCHEMA = "prisma/sqlite/schema.prisma";

function writeSqliteSchema() {
  const src = readFileSync(path.join(root, PG_SCHEMA), "utf8");
  const out = src
    .replace(/provider(\s*)=\s*"postgresql"/, 'provider$1= "sqlite"')
    .replace(/^\s*directUrl\s*=.*\n/m, "");
  if (out === src) throw new Error(`Could not find provider = "postgresql" in ${PG_SCHEMA}`);
  const header =
    "// GENERATED by scripts/prisma.mjs from prisma/schema.prisma — do not edit.\n" +
    "// SQLite paths in DATABASE_URL are relative to this folder, e.g. file:../dev.db\n";
  const dest = path.join(root, SQLITE_SCHEMA);
  mkdirSync(path.dirname(dest), { recursive: true });
  writeFileSync(dest, header + out);
}

const schema = isSqlite ? SQLITE_SCHEMA : PG_SCHEMA;
if (isSqlite) writeSqliteSchema();

function prisma(...args) {
  const bin = path.join(root, "node_modules", ".bin", process.platform === "win32" ? "prisma.cmd" : "prisma");
  try {
    execFileSync(bin, [...args, "--schema", schema], { stdio: "inherit", cwd: root, env: process.env });
  } catch (e) {
    console.error(`[prisma] \`prisma ${args.join(" ")}\` failed.`);
    process.exit(typeof e.status === "number" ? e.status : 1);
  }
}

function migrate() {
  if (!url) {
    const msg = "[prisma] DATABASE_URL is not set — skipping `prisma migrate deploy`.";
    if (process.env.VERCEL_ENV === "production") {
      console.error(msg + " Refusing to build production without a database.");
      process.exit(1);
    }
    console.warn(msg);
    return;
  }
  prisma("migrate", "deploy");
}

const [cmd = "generate", ...rest] = process.argv.slice(2);
console.log(`[prisma] ${cmd} using ${isSqlite ? "SQLite" : "PostgreSQL"} schema (${schema})`);
switch (cmd) {
  case "generate":
    prisma("generate", ...rest);
    break;
  case "migrate":
    migrate();
    break;
  case "setup":
    migrate();
    prisma("generate");
    break;
  case "dev-migrate":
    prisma("migrate", "dev", ...rest);
    break;
  default:
    console.error(`Unknown command: ${cmd}`);
    process.exit(1);
}
